type Seed = {
  id: string;
  number: number;
  topic: string;
  goal: string;
  tasks: string[];
  subject: string;
  personal: string;
  meta: string;
  keywords: string[];
  warmup: string;
  rule: string;
  practice: string;
  independent: string;
  challenge: string;
};

function stages(seed: Seed): LessonStage[] {
  return [
    { id: "org", title: "Организационный момент", minutes: 2, text: "Проверить готовность класса и открыть тему на доске." },
    { id: "warmup", title: "Актуализация", minutes: 7, text: seed.warmup },
    { id: "new", title: "Изучение нового", minutes: 15, text: seed.rule },
    { id: "practice", title: "Закрепление", minutes: 12, text: seed.practice },
    { id: "independent", title: "Самостоятельная работа", minutes: 6, text: seed.independent },
    {
      id: "close",
      title: "Рефлексия и домашнее задание",
      minutes: 3,
      text: `Назвать правило по теме «${seed.topic}» и записать домашнее задание.`,
    },
  ];
}

function lesson(seed: Seed): ThematicLesson {
  const content: LessonContent = {
    goal: seed.goal,
    tasks: seed.tasks.join("\n"),
    results: { subject: seed.subject, personal: seed.personal, meta: seed.meta },
    keywords: seed.keywords.join(", "),
    challenge: seed.challenge,
    stages: stages(seed),
  };
  return { id: seed.id, number: seed.number, topic: seed.topic, content };
}

